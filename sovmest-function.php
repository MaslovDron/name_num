/**
 * Получить полный разбор совместимости
 */
function getFullCompatibilityInterpretation($compatibility, $numbers1, $numbers2) {
    $percentage = $compatibility['percentage'];
    $level = $compatibility['level'];
    
    $levelInfo = getCompatibilityLevelDescription($percentage, $level);
    
    // Получаем советы по укреплению отношений
    $strengtheningAdvice = getStrengtheningAdvice($percentage, $numbers1, $numbers2, $level);
    
    // Вычисляем разницу чисел (для расшифровок)
    $nameDiff = abs($numbers1['name'] - $numbers2['name']);
    $soulDiff = abs($numbers1['soul'] - $numbers2['soul']);
    $personalityDiff = abs($numbers1['personality'] - $numbers2['personality']);
    $karmicDiff = abs($numbers1['karmic'] - $numbers2['karmic']);
    
    // Получаем расшифровки по каждому критерию
    $nameInterpretation = getNameNumberInterpretation($nameDiff, $numbers1['name'], $numbers2['name']);
    $soulInterpretation = getSoulNumberInterpretation($soulDiff, $numbers1['soul'], $numbers2['soul']);
    $personalityInterpretation = getPersonalityNumberInterpretation($personalityDiff, $numbers1['personality'], $numbers2['personality']);
    $karmicInterpretation = getKarmicNumberInterpretation($karmicDiff, $numbers1['karmic'], $numbers2['karmic']);
    
    $generalAdvice = getGeneralAdvice($percentage);
    
    // Определяем иконку
    if ($percentage >= 85) $levelIcon = '💎';
    elseif ($percentage >= 70) $levelIcon = '👍';
    elseif ($percentage >= 50) $levelIcon = '🤔';
    elseif ($percentage >= 30) $levelIcon = '⚠️';
    else $levelIcon = '⚡';
    
    return [
        'level' => $level,
        'level_icon' => $levelIcon,
        'percentage' => $percentage,
        'short_description' => $levelInfo['short'],
        'full_description' => $levelInfo['full'],
        'advice' => $levelInfo['advice'],
        'strengthening_advice' => $strengtheningAdvice,
        'name_interpretation' => $nameInterpretation,
        'soul_interpretation' => $soulInterpretation,
        'personality_interpretation' => $personalityInterpretation,
        'karmic_interpretation' => $karmicInterpretation,
        'general_advice' => $generalAdvice
    ];
}

